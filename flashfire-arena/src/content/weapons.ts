export function theoreticalTimeToKill(weapon: WeaponDefinition, targetHealth = 100): number {
  const damagePerShot = weapon.damage * weapon.pellets;
  const shots = Math.ceil(targetHealth / damagePerShot);
  return Math.max(0, shots - 1) * weapon.cadenceMs;
}
